"""The names ``paperpush validate --disable-NAME`` and ``--enable-NAME`` accept.

A name is a check ID from ``validation_check_ids.json`` (generated by
``scripts/gen_validation_check_count.py``), the dotted start of one, which
covers that whole family (``prose``, ``ai.notes``), or one of :data:`GROUPS`.
Names can be given comma-separated, or in a text file (see :func:`normalize`).
"""

from __future__ import annotations

import difflib
import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Iterable

# Switches wider than an ID prefix: what they cover is not one family of IDs.
GROUPS = {
    "references": "the reference lookups (DOIs, registry searches, retractions, preprint versions, RRIDs, cell lines)",
    "manuscript": "every check that reads the manuscript against the guidelines, and the AI checks",
}

# The families that do not read the manuscript against the guidelines.
NON_MANUSCRIPT_FAMILIES = ("form", "files", "integrity")
_REFERENCE_IDS = ("integrity.dois", "integrity.unmatched_references", "integrity.retractions", "integrity.reference_versions", "rigor.rrids", "rigor.cell_lines")


@lru_cache(maxsize=1)
def known_ids() -> tuple[str, ...]:
    """Every check ID paperpush can report."""
    path = Path(__file__).with_name("validation_check_ids.json")
    return tuple(json.loads(path.read_text(encoding="utf-8")))


def _valid_names() -> set[str]:
    names = set(GROUPS)
    for check_id in known_ids():
        parts = check_id.split(".")
        names.update(".".join(parts[: n + 1]) for n in range(len(parts)))
    return names


def _canonical(raw: str) -> str:
    return raw.strip().lower().replace("-", "_").removesuffix(".*")


def _names_in_file(path: Path) -> list[str]:
    """The names listed in a text file: comma- or whitespace-separated, ``#`` starts a comment."""
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise ValueError(f"cannot read the list of checks {path}: {exc}") from exc
    return [name for line in text.splitlines() for name in re.split(r"[,\s]+", line.partition("#")[0]) if name]


def _split(raw: str, valid: set[str]) -> list[str]:
    """``raw`` as individual names: a name, a comma-separated list, or a text file of names.

    A valid name is never read as a file, so a file called ``manuscript`` in
    the working directory cannot change what ``--disable-manuscript`` means.
    """
    if _canonical(raw) in valid:
        return [raw]
    if Path(raw).expanduser().is_file():
        return _names_in_file(Path(raw).expanduser())
    pieces = [piece.strip() for piece in raw.split(",") if piece.strip()]
    if len(pieces) > 1:
        return [name for piece in pieces for name in _split(piece, valid)]
    if pieces and pieces[0].lower().endswith(".txt"):
        raise ValueError(f"cannot read the list of checks {pieces[0]}: no such file")
    return pieces


def normalize(names: Iterable[str]) -> list[str]:
    """``names`` in canonical form, without repeats; ValueError on one that names no check.

    Each item is a name, a comma-separated list of names, or the path of a text
    file listing them (comma- or whitespace-separated, ``#`` starts a comment).
    Hyphens may stand for underscores (``cover-letter.date``), and a trailing
    ``.*`` is allowed because the documentation writes the numbered families
    that way.
    """
    names = list(names)
    # No names, no lookup: the generator of the ID file calls this with none.
    if not names:
        return []
    valid = _valid_names()
    out: list[str] = []
    for raw in (name for item in names for name in _split(item, valid)):
        name = _canonical(raw)
        if name not in valid:
            close = difflib.get_close_matches(name, sorted(valid), n=3, cutoff=0.6)
            hint = f"; did you mean {' or '.join(close)}?" if close else ""
            raise ValueError(f"unknown check '{raw}'{hint or '.'} See https://paperpush.readthedocs.io/en/latest/validation-checks.html for the check IDs.")
        if name not in out:
            out.append(name)
    if not out:
        # An empty --enable list would otherwise quietly run every check.
        raise ValueError(f"no check names in {', '.join(repr(n) for n in names)}")
    return out


def _covered(name: str) -> list[str]:
    return [i for i in known_ids() if i == name or i.startswith(name + ".")]


def _group_ids(group: str) -> list[str]:
    if group == "references":
        return list(_REFERENCE_IDS)
    return [i for i in known_ids() if i.split(".")[0] not in NON_MANUSCRIPT_FAMILIES]


def select(disable: Iterable[str], enable: Iterable[str]) -> tuple[list[str], list[str]]:
    """``disable`` and ``enable`` normalized; ValueError when they contradict each other."""
    disable, enable = normalize(disable), normalize(enable)
    for name in enable:
        if name in disable:
            raise ValueError(f"--enable-{name} and --disable-{name} contradict each other")
        for group in set(disable) & set(GROUPS):
            ids = _covered(name)
            if ids and set(ids) <= set(_group_ids(group)):
                raise ValueError(f"--enable-{name} cannot be combined with --disable-{group}, which turns it off")
    return disable, enable


def expand_enabled(enable: Iterable[str]) -> list[str]:
    """``enable`` with each group replaced by the names it covers, which an ID can be matched against."""
    out: list[str] = []
    for name in enable:
        if name == "references":
            members = list(_REFERENCE_IDS)
        elif name == "manuscript":
            members = sorted({i.split(".")[0] for i in _group_ids(name)})
        else:
            members = [name]
        out.extend(m for m in members if m not in out)
    return out


def matching(check_id: str, names: Iterable[str]) -> str:
    """The first of ``names`` that covers ``check_id``, or ``""`` when none does."""
    return next((n for n in names if check_id == n or check_id.startswith(n + ".")), "")


def most_specific(check_id: str, names: Iterable[str]) -> str:
    """The longest of ``names`` that covers ``check_id``, or ``""`` when none does."""
    return max((n for n in names if matching(check_id, [n])), key=len, default="")


def off_reason(check_id: str, disable: Iterable[str], enable: Iterable[str] = ()) -> str:
    """Why ``check_id`` is switched off (the flag to name in the report), or ``""`` when it runs.

    With any ``enable`` names only those checks run. A check both cover goes
    with the more specific name, so ``--enable-prose --disable-prose.spelling``
    runs prose without spelling, and ``enable`` must already be expanded (see
    :func:`expand_enabled`).
    """
    enable = tuple(enable)
    off, on = most_specific(check_id, disable), most_specific(check_id, enable)
    if off and len(off) >= len(on):
        return f"--disable-{off}"
    if enable and not on:
        return "not among the --enable-* checks"
    return ""


def reads_manuscript(disable: Iterable[str], enable: Iterable[str]) -> bool:
    """Whether any check that reads the manuscript is left on."""
    disable, enable = tuple(disable), tuple(expand_enabled(enable))
    if "manuscript" in disable:
        return False
    return not enable or any(not off_reason(i, disable, enable) for i in _group_ids("manuscript"))
