#!/usr/bin/env python3
"""Refresh paperpush/venue_metrics.json (OpenAlex 2-year mean citedness per venue).

Needs network access; set OPENALEX_API_KEY to use your own OpenAlex budget.
Not run by the pre-commit hook, since the numbers come from the network: run it
before a release, or after adding a venue.

A venue already in the file keeps its OpenAlex source and only gets fresh
numbers. To fix a wrong match, edit that venue's ``openalex_id`` by hand (or
delete the entry to have it looked up by name again) and re-run.

    python scripts/gen_venue_metrics.py
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ["PAPERPUSH_VENUE_DATA"] = "bundled"

from paperpush import venue_metrics  # noqa: E402
from paperpush.database import list_venues  # noqa: E402

NOTE = (
    "OpenAlex 2-year mean citedness per venue (an open counterpart of the Journal Impact Factor, not the Clarivate figure). "
    "Generated by scripts/gen_venue_metrics.py; edit a venue's openalex_id to fix a wrong match, then re-run."
)


def main() -> int:
    previous = venue_metrics.load()
    metrics, unmatched, failed = venue_metrics.build(list_venues(), previous)
    # A failed lookup keeps the venue's previous entry rather than blanking it.
    for item in failed:
        slug = item.split(" ", 1)[0]
        if slug in previous:
            metrics[slug] = previous[slug]
    data = {"$comment": NOTE, **dict(sorted(metrics.items()))}
    venue_metrics.METRICS_FILE.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {venue_metrics.METRICS_FILE.relative_to(ROOT)}: {len(metrics)} venues")
    for slug in metrics:
        if slug not in previous:
            print(f"  new match: {slug} -> {metrics[slug]['openalex_name']} ({metrics[slug]['openalex_id']}); check it is the right journal")
    if unmatched:
        print("no OpenAlex match (left blank; add an openalex_id by hand to fix): " + ", ".join(unmatched))
    if failed:
        print("lookup failed (previous value kept, re-run later): " + "; ".join(failed))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
